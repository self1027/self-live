const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname,'../.native-deps/gstreamer');
const output = path.resolve(__dirname,'../.native-deps/runtime');
const plugins = ['gstcoreelements.dll','gstapp.dll','gstd3d11.dll','gstamfcodec.dll','gstnvcodec.dll','gstqsv.dll','gstvideoparsersbad.dll','gstrtp.dll','gstrtpmanager.dll','gstwebrtc.dll','gstnice.dll','gstdtls.dll','gstsrtp.dll','gstsctp.dll'];
const vswhere=path.join(process.env['ProgramFiles(x86)'],'Microsoft Visual Studio/Installer/vswhere.exe');
const installation=execFileSync(vswhere,['-latest','-products','*','-requires','Microsoft.VisualStudio.Component.VC.Tools.x86.x64','-property','installationPath'],{encoding:'utf8',windowsHide:true}).trim();
const redistRoot=path.join(installation,'VC/Redist/MSVC');
const redistVersion=fs.readdirSync(redistRoot).filter(name=>/^\d+(\.\d+)+$/.test(name)).sort((a,b)=>a.localeCompare(b,undefined,{numeric:true})).at(-1);
const crt=path.join(redistRoot,redistVersion,'x64/Microsoft.VC143.CRT');
function dependencyPath(dll) {
  const sdk=path.join(root,'bin',dll); if(fs.existsSync(sdk))return sdk;
  if (/^(?:vcruntime140(?:_1)?|msvcp140(?:_[12]|_atomic_wait|_codecvt_ids)?|concrt140)\.dll$/i.test(dll)) {
    const runtime=path.join(crt,dll); if(fs.existsSync(runtime))return runtime;
    throw new Error(`Runtime MSVC redistribuivel ausente: ${dll}`);
  }
  return null;
}

// Copy the transitive PE imports from this pinned SDK, not the whole SDK and
// unrelated codecs. Windows/driver DLLs continue to come from the target PC.
function imports(file) {
  const data = fs.readFileSync(file), pe = data.readUInt32LE(0x3c), count = data.readUInt16LE(pe+6), optionalSize = data.readUInt16LE(pe+20), optional = pe+24;
  const directory = optional + (data.readUInt16LE(optional) === 0x20b ? 112 : 96), sections = optional+optionalSize;
  function offset(rva) {
    for (let i=0;i<count;i++) { const entry=sections+i*40, virtualSize=data.readUInt32LE(entry+8), address=data.readUInt32LE(entry+12), size=data.readUInt32LE(entry+16);
      if (rva>=address && rva<address+Math.max(virtualSize,size)) return data.readUInt32LE(entry+20)+rva-address;
    }
    throw new Error(`RVA invalido em ${path.basename(file)}`);
  }
  const result = [];
  for (const [index,stride,nameOffset] of [[1,20,12],[13,32,4]]) {
    const rva = data.readUInt32LE(directory+index*8); if (!rva) continue;
    for (let descriptor=offset(rva);;descriptor+=stride) {
      const nameRva=data.readUInt32LE(descriptor+nameOffset); if (!nameRva) break;
      const start=offset(nameRva), end=data.indexOf(0,start); result.push(data.toString('ascii',start,end));
    }
  }
  return result;
}
const visited = new Set();
function copy(source, relative) {
  const normalized = path.resolve(source).toLowerCase(); if (visited.has(normalized)) return;
  visited.add(normalized);
  const target=path.join(output,relative); fs.mkdirSync(path.dirname(target),{recursive:true}); fs.copyFileSync(source,target);
  for (const dll of imports(source)) {
    const dependency = dependencyPath(dll);
    if (dependency) copy(dependency,path.join('bin',dll));
  }
}
fs.mkdirSync(output,{recursive:true});
// This staging folder is exclusively generated by this script. Stale plugins
// would invalidate the fixed plugin set and the dependency test.
const resolved=fs.realpathSync(output), expected=path.resolve(__dirname,'../.native-deps/runtime');
if (resolved.toLowerCase() !== expected.toLowerCase()) throw new Error('Diretorio de staging inesperado.');
for (const entry of fs.readdirSync(output)) fs.rmSync(path.join(output,entry),{recursive:true,force:true});
for (const plugin of plugins) copy(path.join(root,'lib/gstreamer-1.0',plugin),path.join('lib/gstreamer-1.0',plugin));
copy(path.join(root,'libexec/gstreamer-1.0/gst-plugin-scanner.exe'),'libexec/gstreamer-1.0/gst-plugin-scanner.exe');
for (const dll of imports(path.resolve(__dirname,'../native/bin/native-video.exe'))) {
  const dependency=dependencyPath(dll); if (dependency) copy(dependency,path.join('bin',dll));
}
const licenses=path.join(root,'share/licenses');
if (fs.existsSync(licenses)) fs.cpSync(licenses,path.join(output,'share/licenses'),{recursive:true});
fs.writeFileSync(path.join(output,'SDK.txt'),'GStreamer 1.28.8 MSVC x64. Official unmodified dynamically linked binaries.\nhttps://gstreamer.freedesktop.org/pkg/windows/1.28.8/msvc/\nhttps://gstreamer.freedesktop.org/src/\n');
console.log(`Runtime portatil: ${visited.size} binarios e avisos do SDK em ${output}`);
